#!/usr/bin/env python3
"""Writes modules/subagents/fan-out-run.js: the texts of the fan-out explainer, word for word from the recorded
run (recordings/subagents/fan-out/codebase-opus-5-5/run-1), so none of them is retyped by hand."""
import html, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
RUN = ROOT / "recordings/subagents/fan-out/codebase-opus-5-5/run-1"
CODE = ROOT / "recordings/subagents/fan-out/fixture-codebase/base"


def jsonl(p):
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()]


def result_text(c):
    c = c.get("content")
    return "".join(x.get("text", "") for x in c) if isinstance(c, list) else (c or "")


def walk(msgs):
    """The agent's tool calls in order, each with its result and the context size of the message that made it."""
    results = {c["tool_use_id"]: result_text(c) for m in msgs if m.get("type") == "user" and isinstance(m["message"]["content"], list)
               for c in m["message"]["content"] if c.get("type") == "tool_result"}
    calls, texts, seen = [], [], set()
    for m in msgs:
        if m.get("type") != "assistant":
            continue
        u = m["message"]["usage"]
        ctx = u["input_tokens"] + u["cache_read_input_tokens"] + u["cache_creation_input_tokens"]
        for c in m["message"]["content"]:
            if c.get("type") == "tool_use" and c["id"] not in seen:
                seen.add(c["id"])
                calls.append({"name": c["name"], "input": c["input"], "ctx": ctx, "result": results.get(c["id"], "")})
            elif c.get("type") == "text" and c["text"] not in texts:
                texts.append(c["text"])
    return calls, texts


def terminal(md):
    """Markdown as the terminal shows it, as HTML: bold kept, headings bold, backticks dropped."""
    out = []
    for line in html.escape(md, quote=False).split("\n"):
        line = re.sub(r"^#+ (.*)$", r"**\1**", line)
        line = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", line)
        out.append(line.replace("`", ""))
    return "\n".join(out)


def plain(md):
    return re.sub(r"\*\*(.+?)\*\*", r"\1", md).replace("`", "")


main = jsonl(RUN / "transcript.jsonl")
main_calls, says = walk(main)
prompts = {c["input"]["description"]: c["input"]["prompt"] for c in main_calls if c["name"] == "Agent"}

subs, reports, end_ctx = {}, {}, {}
for meta in sorted((RUN / "session/subagents").glob("*.meta.json")):
    who = json.loads(meta.read_text())["description"]
    calls, _ = walk(jsonl(meta.with_name(meta.name.removesuffix(".meta.json") + ".jsonl")))
    reports[who] = next(c["input"]["message"] for c in calls if c["name"] == "SubagentHandback")
    end_ctx[who] = calls[-1]["ctx"]
    subs[who] = [{"name": c["name"], "cmd": c["input"].get("command", c["input"].get("file_path", "")), "ctx": c["ctx"],
                  "result": c["result"]} for c in calls if c["name"] != "SubagentHandback"]

probe = next(c for c in subs["Review API and auth"] if "probe2.py" in c["cmd"])
bash = [c for c in main_calls if c["name"] == "Bash"]

data = {
    "PROMPT": next(m["message"]["content"] for m in main if m.get("type") == "user" and isinstance(m["message"]["content"], str)),
    "LIST_CMD": bash[0]["input"]["command"],
    "LIST_OUT": bash[0]["result"].rstrip("\n"),
    "PROMPTS": prompts,
    "SUB_CALLS": {k: [{"name": c["name"], "cmd": c["cmd"], "ctx": c["ctx"]} for c in v] for k, v in subs.items()},
    "SUB_END_CTX": end_ctx,
    "PROBE": probe["cmd"].split("<<'EOF'\n", 1)[1].split("\nEOF\n", 1)[0],
    "PROBE_OUT": probe["result"].rstrip("\n"),
    "REPORTS": {k: terminal(v) for k, v in reports.items()},
    "REPORTS_TEXT": {k: plain(v) for k, v in reports.items()},
    "SAYS": [terminal(s) for s in says[:-1]],
    "SPOT_CMD": bash[1]["input"]["command"],
    "SPOT_OUT": bash[1]["result"].rstrip("\n"),
    "REPLY": terminal(says[-1]),
    "REPLY_TEXT": plain(says[-1]),
    "CONFIG_PY": (CODE / "config.py").read_text().rstrip("\n"),
    "NGINX": (CODE / "deployment/nginx/microblog").read_text().rstrip("\n"),
}
out = ["// Generated by tools/extract/fan-out-run.py from recordings/subagents/fan-out/codebase-opus-5-5/run-1. Don't edit by hand.", ""]
for k, v in data.items():
    out.append(f"export const {k} = {json.dumps(v, ensure_ascii=False, indent=2 if isinstance(v, (dict, list)) else None)};")
(ROOT / "modules/subagents/fan-out-run.js").write_text("\n".join(out) + "\n")
for k, v in data.items():
    print(k, v if isinstance(v, (int, dict)) and not isinstance(v, dict) else len(v) if not isinstance(v, dict) else {kk: vv if isinstance(vv, int) else len(vv) for kk, vv in v.items()})
